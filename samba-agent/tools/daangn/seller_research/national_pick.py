def tol(cs): return sum(1 for c in cs if c['new'] and c['price'] >= 30000 and not c['buynow'] and not c['sold'])
def nh(cs): return sum(1 for c in cs if c['new'] and c['price'] >= 30000 and not c['sold'])
def act(cs): return sum(1 for c in cs if not c['sold']) / len(cs)
def sc(cs): return 2 * tol(cs) + nh(cs) + 4 * max(0, act(cs) - 0.8) / 0.2


def hav(a, b):
  R = 6371; p1, p2 = math.radians(a[0]), math.radians(b[0]); dl = math.radians(b[1] - a[1]); dp = p2 - p1
  h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
  return 2 * R * math.asin(math.sqrt(h))


agg = collections.defaultdict(list); seen = set()
for k, v in D.items():
  r = v.get('region'); cs = v.get('cards') or []
  if not r or not cs: continue
  key = (r[0][:2], r[1])
  if key not in Z: continue
  if r[1] == '경산시' and r[2] == '하양읍':       # 잘못된 id 가 돌려주는 기본 지역은 한 번만
    if (key, r[2]) in seen: continue
    seen.add((key, r[2]))
  agg[key].append((r[2], cs))
allsc = [sc(c) for v in agg.values() for _, c in v]; prior = sum(allsc) / len(allsc); K = 3
S = {}
for key, v in agg.items():
  n = len(v); raw = sum(sc(c) for _, c in v) / n
  S[key] = dict(score=(n * raw + K * prior) / (n + K), raw=raw, n=n, act=round(sum(act(c) for _, c in v) / n * 100), tol=round(sum(tol(c) for _, c in v) / n, 1),
                nh=round(sum(nh(c) for _, c in v) / n, 1), dongs=[b[0] for b in sorted(v, key=lambda x: -sc(x[1]))[:2]])
keys = list(S)

